"""Bundle texts/*.json into data/texts.js (run after adding or editing a text).

Each text file: {id, series: myth|why|true|culture|story, chapter, title, title_en, level: A2|A2+|B1|B1+,
theme, summary_en, paragraphs: [[[greek, english], ...], ...], notes: [{form, lemma, gloss, note}],
questions: [{q, q_en, options: [...], answer: index}]}
"""
import json, glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
texts = []
for fn in sorted(glob.glob(os.path.join(ROOT, 'texts', '*.json'))):
    t = json.load(open(fn, encoding='utf-8'))
    body = ' '.join(s[0] for p in t['paragraphs'] for s in p)
    missing = [n['form'] for n in t.get('notes', []) if n['form'] not in body]
    if missing:
        print('warning:', os.path.basename(fn), 'note forms not in text:', missing)
    texts.append(t)
order = {'myth': 0, 'why': 1, 'true': 2, 'culture': 3, 'story': 4}
texts.sort(key=lambda t: (order.get(t['series'], 2), t.get('chapter', 0)))
out = os.path.join(ROOT, 'data', 'texts.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Graded readers. Generated by tools/build_texts.py from texts/*.json: edit those, not this. */\n')
    f.write('window.GR_TEXTS=' + json.dumps(texts, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(texts), 'texts ->', out)
