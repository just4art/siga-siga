"""Copy words.csv into data/my-words.js, the list the app uses before you connect the real file.
my-words.js is personal, so it is in .gitignore and not published."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'A2_exam', 'words.csv')
text = open(src, encoding='utf-8').read()
with open(os.path.join(ROOT, 'data', 'my-words.js'), 'w', encoding='utf-8') as f:
    f.write('/* Snapshot of words.csv. Generated by tools/snapshot_words.py. */\n')
    f.write('window.GR_WORDS_CSV=' + json.dumps(text, ensure_ascii=False) + ';\n')
print('snapshot of', src, len(text.splitlines()) - 1, 'words')
